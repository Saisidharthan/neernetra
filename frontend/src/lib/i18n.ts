export function t(lang: Language, key: string): string {
  return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS['en']?.[key] ?? key;
}

export function tf(lang: Language, key: string, vars: Record<string, string | number>): string {
  return t(lang, key).replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

export function isLanguage(value: string): value is Language {
  return LANGUAGES.some((l) => l.code === value);
}

export function toEngineLang(lang: Language): Lang {
  return lang === 'hi' || lang === 'as' ? lang : 'en';
}

